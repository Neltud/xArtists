-- xArtists xArt-ID v1 — schema CANDIDATE / NOT APPLIED to Neon or Render.
-- Never run this migration without tenant/ACL design, backup and review.
-- Registration anchors identify a CLAIM under one namespace, not authentic works.
BEGIN;

CREATE TABLE IF NOT EXISTS xart_id_registrations (
  art_id            TEXT PRIMARY KEY CHECK (art_id ~ '^xart:v1:[a-f0-9]{64}$'),
  creator_namespace TEXT NOT NULL CHECK (length(creator_namespace) BETWEEN 3 AND 128),
  edition_id        TEXT NOT NULL CHECK (length(edition_id) BETWEEN 1 AND 48),
  master_sha256     TEXT NOT NULL CHECK (master_sha256 ~ '^[a-f0-9]{64}$'),
  tenant_id         TEXT NOT NULL,
  review_status     TEXT NOT NULL DEFAULT 'unverified'
                    CHECK (review_status IN ('unverified', 'review_required', 'reviewed', 'revoked')),
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (creator_namespace, master_sha256, edition_id, tenant_id)
);

-- Store only evidence metadata and references, NOT scans of contracts,
-- original private photos, buyer PII, registry raw records or bearer tokens.
CREATE TABLE IF NOT EXISTS xart_id_evidence_events (
  evidence_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  art_id            TEXT NOT NULL REFERENCES xart_id_registrations(art_id) ON DELETE RESTRICT,
  tenant_id         TEXT NOT NULL,
  evidence_digest   TEXT NOT NULL CHECK (evidence_digest ~ '^[a-f0-9]{64}$'),
  event_type        TEXT NOT NULL CHECK (event_type IN
                    ('intake','hash_check','c2pa_check','visual_candidate','provenance_claim',
                     'registry_screen','onchain_snapshot','curator_review','revocation','reassessment')),
  source_class      TEXT NOT NULL CHECK (source_class IN
                    ('artist_claim','curator_review','external_provider','chain_read','system')),
  evidence_ref      TEXT,
  source_checked_at TIMESTAMPTZ,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (art_id, evidence_digest, event_type)
);

CREATE INDEX IF NOT EXISTS xart_id_evidence_events_art_time_idx
  ON xart_id_evidence_events (art_id, created_at DESC);

-- Append-only events, including revocations; a separate privileged review
-- record must document who verified evidence and whether access was authorized.
CREATE OR REPLACE FUNCTION xart_id_deny_evidence_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'xart_id_evidence_is_append_only';
END $$;

DROP TRIGGER IF EXISTS xart_id_evidence_immutable ON xart_id_evidence_events;
CREATE TRIGGER xart_id_evidence_immutable
  BEFORE UPDATE OR DELETE ON xart_id_evidence_events
  FOR EACH ROW EXECUTE FUNCTION xart_id_deny_evidence_mutation();

-- Enable RLS before creating any API access. NO policies provided here;
-- production deployment requires scoped actor grants, policy coverage,
-- the FORCE RLS decision and isolation tests before any traffic.
ALTER TABLE xart_id_registrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE xart_id_evidence_events ENABLE ROW LEVEL SECURITY;

COMMIT;

